CREATE TABLE media_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
    is_public BOOLEAN NOT NULL DEFAULT FALSE
);

ALTER TABLE photos ADD COLUMN category_id BIGINT REFERENCES media_categories(id);
ALTER TABLE upload_jobs ADD COLUMN category_id BIGINT REFERENCES media_categories(id);
ALTER TABLE upload_jobs ADD COLUMN welcome_revision BIGINT CHECK (welcome_revision >= 0);
CREATE INDEX photos_category_page ON photos(category_id, id DESC);

